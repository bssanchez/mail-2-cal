def email_with(ics: str, *, also_attachment: bool = True) -> bytes:
    """Correo multipart como el de Outlook: texto, calendario en línea y .ics adjunto."""
    from email.message import EmailMessage

    msg = EmailMessage()
    msg["From"] = "ana@cliente.com"
    msg["To"] = "yo@miempresa.com"
    msg["Subject"] = "Invitación"
    msg.set_content("Te invito a una reunión.")
    msg.add_alternative(ics, subtype="calendar", params={"method": "REQUEST"})
    if also_attachment:
        msg.add_attachment(ics.encode(), maintype="application", subtype="ics", filename="invite.ics")
    return msg.as_bytes()
